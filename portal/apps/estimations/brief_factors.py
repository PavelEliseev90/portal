# По умолчанию не крутят звёзды: это про спрос, не про состояние кузова.
# Включить галочкой «в шкале» на странице весов.
SALES_STAR_KEYS = frozenset({'our_sales_hot', 'our_sales_slow', 'our_sales_none'})


def factor_defaults_map():
    return {
        key: {
            'key': key,
            'label': label,
            'group': group,
            'weight': float(weight),
            'objection': objection,
            'answer': answer,
        }
        for key, label, group, weight, objection, answer in DEFAULT_FACTORS
    }


def load_factor_config():
    """Дефолты + веса из БД. inactive и sales-пункты по умолчанию не в шкале."""
    cfg = factor_defaults_map()
    # Продажи — opt-in: без строки в БД с active=True в звёзды не входят
    for key in SALES_STAR_KEYS:
        cfg.pop(key, None)
    try:
        from estimations.models import EstimationBriefFactor
        for row in EstimationBriefFactor.objects.all():
            if not row.active:
                cfg.pop(row.key, None)
                continue
            item = cfg.get(row.key) or {
                'key': row.key,
                'label': row.label,
                'group': row.group or 'Прочее',
                'weight': 0.0,
                'objection': '',
                'answer': '',
            }
            item['weight'] = float(row.weight)
            if row.label:
                item['label'] = row.label
            if row.objection:
                item['objection'] = row.objection
            if row.answer:
                item['answer'] = row.answer
            if row.group:
                item['group'] = row.group
            cfg[row.key] = item
    except Exception:
        pass
    return cfg


